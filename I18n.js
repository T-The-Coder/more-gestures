function lang(l) { return String(l || "en").toLowerCase().indexOf("de") === 0 ? "de" : "en" }

// Missing German keys fall back to English, then to the key itself (visible, not blank).
function tr(l, key) {
  var table = STRINGS[lang(l)]
  if (Object.prototype.hasOwnProperty.call(table, key)) return table[key]
  return Object.prototype.hasOwnProperty.call(STRINGS.en, key) ? STRINGS.en[key] : key
}

// Keys.comboFromText error code -> message.
function keyError(l, code) {
  var map = { "empty": "err_empty", "modifier": "err_modifier", "missing-key": "err_missingKey",
              "key": "err_key", "duplicate": "err_duplicate" }
  return tr(l, map[code] || "err_action")
}

if (typeof module !== "undefined") module.exports = { STRINGS: STRINGS, lang: lang, tr: tr, keyError: keyError }
